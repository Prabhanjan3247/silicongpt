import type { KeyboardEvent } from 'react';
import clsx from 'clsx';
import { FileText, Link2, Sparkles, X } from 'lucide-react';
import type { HdlLanguage } from '../../services/types';
import { formatNumber } from '../../lib/format';
import { Button } from '../ui/Button';
import { Card } from '../ui/Card';
import { Select } from '../ui/Select';
import { TextArea } from '../ui/TextArea';

/** Same limit as the architect agent (backend/app/agents/architect.py MAX_SPEC_CHARS). */
export const MAX_SPEC_CHARS = 100_000;

export const LANGUAGE_OPTIONS: ReadonlyArray<{ value: HdlLanguage; label: string }> = [
  { value: 'verilog', label: 'Verilog-2005 (.v)' },
  { value: 'systemverilog', label: 'SystemVerilog (.sv)' },
];

/** Prompt starters (inputs only - the design is always generated by the backend). */
export const EXAMPLE_PROMPTS: ReadonlyArray<{ label: string; spec: string }> = [
  {
    label: '8-bit ALU',
    spec: 'Create an 8-bit ALU supporting ADD, SUB, AND, OR, XOR and NOT.',
  },
  {
    label: 'Up/down counter',
    spec:
      'Design a 4-bit up/down counter with a synchronous active-high reset, a count enable, a direction input ' +
      '(1 = up, 0 = down) and a terminal-count output that is high when the counter is at its maximum (up) or zero (down).',
  },
  {
    label: 'Synchronous FIFO',
    spec:
      'Create a synchronous FIFO with 16 entries of 8 bits, single clock, active-low asynchronous reset, write and read ' +
      'enables, full and empty flags and an occupancy count output. Writes when full and reads when empty are ignored.',
  },
  {
    label: 'UART transmitter',
    spec:
      'Create a UART transmitter for 8 data bits, no parity and 1 stop bit (8N1). A parameter sets the clock cycles per bit. ' +
      'Inputs: clk, rst_n, start, data[7:0]. Outputs: tx (idles high) and busy.',
  },
  {
    label: 'Traffic light FSM',
    spec:
      'Design a traffic light controller FSM for a two-road intersection with parameterized green and yellow durations ' +
      '(in clock cycles), a pedestrian request input that shortens the current green phase, and one-hot light outputs per road.',
  },
  {
    label: 'Barrel shifter',
    spec:
      'Create a combinational 32-bit barrel shifter with a 5-bit shift amount and a 2-bit opcode: 00 logical left, ' +
      '01 logical right, 10 arithmetic right, 11 rotate right.',
  },
];

export interface SpecFormProps {
  spec: string;
  onSpecChange: (spec: string) => void;
  /** An example prompt was picked (replaces the spec). */
  onPickExample: (spec: string) => void;
  language: HdlLanguage;
  onLanguageChange: (language: HdlLanguage) => void;
  onGenerate: () => void;
  running: boolean;
  /** The selected project and its stored spec (offered as a starting point). */
  project: { id: number; name: string; spec: string } | null;
  /** Project the next request will be associated with (its AI history). */
  linkedProject: { id: number; name: string } | null;
  onUseProjectSpec: () => void;
  onUnlink: () => void;
}

/** Natural-language specification input with example prompts and the HDL language. */
export function SpecForm({
  spec,
  onSpecChange,
  onPickExample,
  language,
  onLanguageChange,
  onGenerate,
  running,
  project,
  linkedProject,
  onUseProjectSpec,
  onUnlink,
}: SpecFormProps) {
  const length = spec.length;
  const tooLong = length > MAX_SPEC_CHARS;
  const canGenerate = spec.trim().length > 0 && !tooLong && !running;
  const projectSpec = project && project.spec.trim() ? project : null;

  const onKeyDown = (event: KeyboardEvent<HTMLTextAreaElement>) => {
    if (event.key === 'Enter' && (event.ctrlKey || event.metaKey)) {
      event.preventDefault();
      if (canGenerate) onGenerate();
    }
  };

  return (
    <Card
      icon={<Sparkles />}
      title="Design specification"
      description="Describe the block in plain language: function, interfaces, widths, clocking and reset. Unclear points are reported back as assumptions and open questions."
    >
      <TextArea
        aria-label="Design specification"
        rows={6}
        value={spec}
        onChange={(e) => onSpecChange(e.target.value)}
        onKeyDown={onKeyDown}
        placeholder="e.g. Create an 8-bit ALU supporting ADD, SUB, AND, OR, XOR and NOT."
        error={tooLong ? `The specification is too long (${formatNumber(length)} characters, limit ${formatNumber(MAX_SPEC_CHARS)}).` : undefined}
        labelAction={
          <span className={clsx('tabular-nums', tooLong && 'text-fail')}>
            {formatNumber(length)} / {formatNumber(MAX_SPEC_CHARS)}
          </span>
        }
        label="Specification"
      />

      <div className="mt-3 flex flex-wrap items-center gap-1.5">
        <span className="mr-1 text-2xs font-medium uppercase tracking-wider text-subtle">Examples</span>
        {EXAMPLE_PROMPTS.map((example) => {
          const active = spec.trim() === example.spec;
          return (
            <button
              key={example.label}
              type="button"
              title={example.spec}
              onClick={() => onPickExample(example.spec)}
              className={clsx(
                'rounded-full border px-2.5 py-1 text-xs transition-colors',
                active
                  ? 'border-accent/50 bg-accent/10 text-[#67e8f9]'
                  : 'border-border-strong bg-surface text-muted hover:border-[#3a4e6e] hover:text-text',
              )}
            >
              {example.label}
            </button>
          );
        })}
        {projectSpec && (
          <button
            type="button"
            onClick={onUseProjectSpec}
            title={`Load the specification stored in project “${projectSpec.name}” and record the generation in its AI history`}
            className="inline-flex items-center gap-1.5 rounded-full border border-blue/35 bg-blue/10 px-2.5 py-1 text-xs text-[#93c5fd] transition-colors hover:bg-blue/20"
          >
            <FileText aria-hidden="true" className="size-3" />
            Spec of {projectSpec.name}
          </button>
        )}
      </div>

      <div className="mt-4 flex flex-wrap items-end gap-3">
        <Select
          label="HDL language"
          value={language}
          onChange={(e) => onLanguageChange(e.target.value === 'systemverilog' ? 'systemverilog' : 'verilog')}
          options={LANGUAGE_OPTIONS}
          containerClassName="w-56"
        />
        {linkedProject && (
          <span className="mb-1 inline-flex items-center gap-1.5 rounded-lg border border-border bg-surface px-2 py-1 text-xs text-muted">
            <Link2 aria-hidden="true" className="size-3.5 text-[#93c5fd]" />
            Recorded in the AI history of <span className="font-medium text-text">{linkedProject.name}</span>
            <button
              type="button"
              onClick={onUnlink}
              aria-label="Do not associate the generation with this project"
              title="Do not associate the generation with this project"
              className="rounded p-0.5 text-subtle hover:bg-hover hover:text-text"
            >
              <X className="size-3" />
            </button>
          </span>
        )}
        <div className="ml-auto flex items-center gap-3">
          <span className="hidden text-2xs text-subtle md:inline">Ctrl+Enter</span>
          <Button variant="primary" size="lg" icon={<Sparkles />} loading={running} disabled={!canGenerate} onClick={onGenerate}>
            {running ? 'Generating…' : 'Generate design'}
          </Button>
        </div>
      </div>
    </Card>
  );
}
